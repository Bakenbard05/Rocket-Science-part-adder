# Reads the flame prefabs of the game out of its asset bundles and writes
# flame-presets.js for the editor: the values of the materials of the stock
# flames, so the editor can start from them and the preview shows the real
# flame instead of a generic one.
#
# Needs UnityPy (pip install UnityPy) and the game installed.
#
#   python generate-flame-presets.py ["<path to the game>"]
#
# The default path is the usual Steam install.
import json
import os
import sys

try:
    import UnityPy
except ImportError:
    print('UnityPy is missing: pip install UnityPy')
    sys.exit(1)

GAME = sys.argv[1] if len(sys.argv) > 1 else r'E:\SteamLibrary\steamapps\common\Rocket Science'
AA = os.path.join(GAME, 'Rocket Science_Data', 'StreamingAssets', 'aa', 'StandaloneWindows64')

PREFABS = os.path.join(AA, 'prefabs_group_assets_all_d659b39e045f1888348eb7711d98451e.bundle')
MESHES = os.path.join(AA, 'meshes_group_assets_all_6306de0d3030c0ffbe9bde43953c8c02.bundle')

FLOAT_KEYS = [
    ('rimPower', '_RimPower'), ('flameLevel', '_FlameLevel'), ('brightness', '_Brightness'),
    ('intensity', '_Intensity'), ('lengthFade', '_LengthFade'), ('blend', '_Blend'),
    ('speed', '_Speed'), ('move', '_Move'), ('pow', '_Pow'), ('totalLength', '_TotalLength'),
]
VEC_KEYS = [
    ('scroll', '_Scroll'), ('flipbook', '_FlipBook'), ('flutter', '_Flutter'),
    ('pulse', '_Pulse'), ('angle', '_Angle'), ('against', '_Against'),
    ('scale', '_Scale'), ('soften', '_Soften'), ('taper', '_Taper'),
]
COLOR_KEYS = [('color', '_Color'), ('rimColor', '_RimColor')]
SMALL_VECTORS = ('scroll', 'flipbook', 'against', 'taper')


def color(rgb):
    return [round(rgb.r, 5), round(rgb.g, 5), round(rgb.b, 5)]


def hexof(rgb):
    return '#' + ''.join('%02x' % max(0, min(255, round(c * 255))) for c in rgb[:3])


def vec(values, count):
    values = list(values[:count]) + [0.0] * max(0, count - len(values))
    return [round(v, 5) for v in values]


def extract():
    env = UnityPy.load(PREFABS, MESHES)
    out = {}

    for obj in env.objects:
        if obj.type.name != 'GameObject':
            continue
        go = obj.read()
        name = go.m_Name
        if not name.endswith('_flame'):
            continue

        entry = {}
        for comp in go.m_Component:
            c = comp.component
            try:
                if c.type.name == 'MeshRenderer':
                    mr = c.read()
                    if not mr.m_Materials:
                        continue
                    props = mr.m_Materials[0].read().m_SavedProperties
                    floats = {n: round(v, 5) for n, v in props.m_Floats}
                    colors = {n: color(v) for n, v in props.m_Colors}
                    entry['floats'] = {k: floats[k] for k in
                                       [s for _, s in FLOAT_KEYS] if k in floats}
                    entry['colors'] = {k: colors[k] for k in
                                       [s for _, s in COLOR_KEYS] if k in colors}
                    for n, v in props.m_TexEnvs:
                        if n == '_Noise':
                            entry['noiseST'] = [round(v.m_Scale.x, 5), round(v.m_Scale.y, 5)]
            except Exception as error:  # a broken flame must not stop the run
                entry.setdefault('errors', []).append(str(error))

        if entry:
            out[name] = entry

    return out


def write_presets(flames, target):
    lines = [
        '// The parameters of the flame prefabs of the game, read out of the assets',
        '// (the materials of the flame prefabs). The editor uses them as presets:',
        '// picking a base flame fills the fields with the values the game uses, so',
        '// the preview shows the stock flame and only the changed values are',
        '// written to flame.json.',
        '//',
        '// The colors of the game are HDR (the rim of engine_0_flame is 44.7), so a',
        '// color carries the hex for the field and the values for the material.',
        '// Generated by generate-flame-presets.py, do not edit by hand.',
        'export const FLAME_PRESETS = {',
    ]

    for name in sorted(flames):
        entry = flames[name]
        floats = entry.get('floats', {})
        colors = entry.get('colors', {})
        params = {}

        for key, shader in FLOAT_KEYS:
            if shader in floats:
                params[key] = round(floats[shader], 4)

        for key, shader in VEC_KEYS:
            if shader in colors:
                count = 2 if key in SMALL_VECTORS else 3
                params[key] = vec(colors[shader], count)

        for key, shader in COLOR_KEYS:
            if shader in colors:
                rgb = colors[shader]
                params[key] = {'hex': hexof(rgb), 'hdr': [round(c, 4) for c in rgb[:3]]}

        if 'noiseST' in entry:
            params['noiseST'] = [round(v, 4) for v in entry['noiseST']] + [0, 0]

        lines.append("  '%s': {" % name)
        lines.append('    params: {')
        for key, value in params.items():
            if isinstance(value, dict):
                lines.append("      %s: { hex: '%s', hdr: [%s] }," % (
                    key, value['hex'], ', '.join(str(v) for v in value['hdr'])))
            elif isinstance(value, list):
                lines.append('      %s: [%s],' % (key, ', '.join(str(v) for v in value)))
            else:
                lines.append('      %s: %s,' % (key, value))
        lines.append('    },')
        lines.append('  },')

    lines.append('};')
    lines.append('')
    open(target, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))


if __name__ == '__main__':
    flames = extract()
    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'flame-presets.js')
    write_presets(flames, target)
    print('written %s (%d flames)' % (target, len(flames)))
